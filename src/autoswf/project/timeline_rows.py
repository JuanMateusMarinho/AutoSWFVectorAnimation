"""What the timeline shows (spec §6, §11): per animated part a header row and one row per layer it moves, each with its
own loop length and its keyframes, generated by the preset or made by hand. Frames are 0-based here."""
from dataclasses import dataclass

LOOP_PARAM = {"Blink": "interval", "Sway": "length", "Twitch": "every", "Pulse": "length"}


@dataclass(frozen=True)
class TimelineRow:
    part: str
    target: str | None           # None: the part's header row
    preset: str
    length: int
    keys: dict[int, str]         # frame -> "generated" or "manual"


def timeline_rows(build) -> list[TimelineRow]:
    if build is None or build.timeline is None:
        return []
    order = list(build.parts.parts) if build.parts is not None else []
    clips = sorted(build.timeline.clips.values(), key=lambda c: order.index(c.part) if c.part in order else len(order))
    rows = []
    for clip in clips:
        preset = clip.preset.name if clip.preset is not None else "Custom"
        tracks = []
        for target, track in clip.tracks.items():
            keys = {f: "manual" if k.manual else "generated" for f, k in track.keys.items() if f < clip.length}
            tracks.append(TimelineRow(clip.part, target, preset, clip.length, keys))
        union: dict[int, str] = {}
        for row in tracks:
            for f, kind in row.keys.items():
                if union.get(f) != "manual":
                    union[f] = kind
        rows.append(TimelineRow(clip.part, None, preset, clip.length, union))
        rows += tracks
    return rows
